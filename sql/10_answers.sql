-- 8. Объясни все четыре принципа ACID на конкретных шагах задания 7 или 8.
-- TODO: напиши решение здесь.

-- Atomicity - это принцип, который гласит, что действия должны быть выполнения
-- все и польностью, либо не быть выполнены вообще. В реляционных базад данных он
-- реализован с помощью транзакций
--
-- Consistensy - это принцип, который гласит, что в базе данных всё будет согласованно.
-- То есть,после каждой завершенной транзакции бд остаётся в корректном состоянии
-- и соблюдает все заданные ограничения целостности
--
-- Isolation - Во время выполнения транзакции параллельные транзакции не должны оказывать
-- влияния на её результат. Изолированность — требование дорогое, поэтому в реальных базах
-- данных существуют режимы, не полностью изолирующие транзакцию
--
-- Durability Независимо от проблем на нижних уровнях (к примеру, обесточивание системы или
-- сбои в оборудовании) изменения, сделанные успешно завершённой транзакцией, должны остаться
-- сохранёнными после возвращения системы в работу

