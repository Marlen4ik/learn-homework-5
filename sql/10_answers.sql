-- 5. Чем INNER JOIN отличается от LEFT JOIN? Приведи пример из задания 4.
-- TODO: напиши решение здесь.

-- Inner join позволяет доставать записи, которые есть в обоих таблицах.
-- Например, если мы соединяем книги и авторов, то останутся только те книги
-- у которых есть авторы и наоборот
-- Left join позволяет доставать записи, которые есть у таблицы, которую мы
-- выбрали (from a), и те записи, которые есть и у первой и второй. Например,
-- все читатели, и читатели у которых есть займы

